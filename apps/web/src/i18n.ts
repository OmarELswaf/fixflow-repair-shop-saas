export function applyLanguage(lang: Language): void {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

export function otherLanguage(lang: Language): Language {
  return lang === 'ar' ? 'en' : 'ar';
}

/** Status keys in workflow order. */
export const REPAIR_STATUSES = [
  'received',
  'diagnosing',
  'awaiting_approval',
  'awaiting_parts',
  'in_repair',
  'quality_check',
  'ready',
  'delivered',
  'cancelled',
  'unrepairable',
] as const;

export type RepairStatus = (typeof REPAIR_STATUSES)[number];

/**
 * Transitions the UI offers from each status. The server is
 * authoritative and rejects illegal transitions (422); this map only
 * decides which buttons to show.
 */
export const ALLOWED_TRANSITIONS: Record<RepairStatus, RepairStatus[]> = {
  received: ['diagnosing', 'cancelled'],
  diagnosing: ['awaiting_approval', 'awaiting_parts', 'in_repair', 'cancelled', 'unrepairable'],
  awaiting_approval: ['in_repair', 'cancelled', 'unrepairable'],
  awaiting_parts: ['in_repair', 'cancelled', 'unrepairable'],
  in_repair: ['quality_check', 'cancelled', 'unrepairable'],
  quality_check: ['ready', 'in_repair', 'unrepairable'],
  ready: ['delivered', 'cancelled'],
  delivered: [],
  cancelled: [],
  unrepairable: [],
};

export const LanguageContext = createContext<Language>('ar');

